/**
 * Regenerates the Drizzle schema and the database function registry from the migrations.
 *
 * Builds a throwaway PostgreSQL cluster, applies `docs/migration/supabase-platform-shim.sql`
 * and every file in `supabase/migrations/` in order, then:
 *
 * - introspects the `public` schema with a pinned drizzle-kit into `src/lib/db/schema.ts`,
 *   keeping the database's snake_case names so rows read the way PostgREST returned them;
 * - reads `pg_proc` into `src/lib/db/functions.ts`: every function the `service_role` may
 *   execute that returns one value (no triggers, no set-returning functions), with its
 *   argument names, types and which ones have defaults.
 *
 * Nothing here touches a hosted database. Needs `initdb`, `pg_ctl` and `psql` from
 * PostgreSQL 17 on PATH, and network access to install a pinned drizzle-kit into a temporary
 * directory. Run `npm run db:generate` after adding a migration, and commit both files.
 */

import { execFileSync } from "node:child_process";
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createServer } from "node:net";
import { tmpdir } from "node:os";
import { join } from "node:path";

/* Drizzle Kit imports drizzle-orm and a driver from its own install, so all three go into a
   throwaway prefix rather than the app's lockfile. */
const DRIZZLE_KIT = ["drizzle-kit@0.31.11", "drizzle-orm@0.45.4", "postgres@3.4.9"];
const DATABASE = "wgi_fresh";
const root = new URL("..", import.meta.url).pathname;
const schemaFile = join(root, "src/lib/db/schema.ts");
const functionsFile = join(root, "src/lib/db/functions.ts");
const banner =
  "/* Generated by scripts/generate-db-schema.mjs from supabase/migrations. Do not edit;\n" +
  "   run `npm run db:generate` after adding a migration. */\n\n";

/** PostgreSQL argument types the registry knows how to accept from TypeScript. */
const ARGUMENT_TYPES = new Map([
  ["bigint", "number"],
  ["boolean", "boolean"],
  ["date", "string"],
  ["integer", "number"],
  ["jsonb", "Json"],
  ["text", "string"],
  ["text[]", "readonly string[]"],
  ["timestamp with time zone", "string"],
  ["uuid", "string"],
  ["uuid[]", "readonly string[]"],
]);

const environment = { ...process.env, LC_ALL: "en_US.UTF-8", LANG: "en_US.UTF-8" };

function run(command, args, options = {}) {
  return execFileSync(command, args, {
    encoding: "utf8",
    env: environment,
    stdio: ["ignore", "pipe", "pipe"],
    ...options,
  });
}

async function freePort() {
  const server = createServer();
  await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
  const { port } = server.address();
  await new Promise((resolve) => server.close(resolve));
  return port;
}

function applyMigrations(psql) {
  psql(["-d", "postgres", "-c", `create database ${DATABASE}`]);
  psql(["-d", DATABASE, "-f", join(root, "docs/migration/supabase-platform-shim.sql")]);
  const migrations = readdirSync(join(root, "supabase/migrations"))
    .filter((name) => name.endsWith(".sql"))
    .sort();
  for (const name of migrations) {
    psql(["-d", DATABASE, "--single-transaction", "-f", join(root, "supabase/migrations", name)]);
  }
  return migrations.length;
}

function generateSchema(url, workDir) {
  const out = join(workDir, "pull");
  const kit = join(workDir, "kit");
  run("npm", ["install", "--prefix", kit, "--no-save", "--no-audit", "--no-fund", ...DRIZZLE_KIT]);
  run(join(kit, "node_modules/.bin/drizzle-kit"), [
    "pull",
    "--dialect=postgresql",
    `--url=${url}`,
    "--schemaFilters=public",
    "--introspect-casing=preserve",
    `--out=${out}`,
  ]);
  let source = readFileSync(join(out, "schema.ts"), "utf8");
  source = source.replaceAll(
    /^\s*\/\/ You can use \{ mode: "bigint" \} if numbers are exceeding js number limitations\n/gmu,
    "",
  );
  // A table whose extra config only holds SQL checks never reads its columns argument.
  source = source
    .split(/(?=^export const )/mu)
    .map((table) => (table.includes("table.") ? table : table.replace("(table) => [", "() => [")))
    .join("");
  // The one foreign key out of `public` points at Supabase Auth's users table; declare its key.
  if (source.includes("foreignColumns: [users.id]")) {
    source = source
      .replace(/^import \{ pgTable, /u, "import { pgSchema, pgTable, ")
      .replace(
        /^(import \{ sql \} from "drizzle-orm"\n)/mu,
        '$1\nconst auth = pgSchema("auth");\n' +
          'const authUsers = auth.table("users", { id: uuid().primaryKey() });\n',
      )
      .replaceAll("foreignColumns: [users.id]", "foreignColumns: [authUsers.id]");
  }
  writeFileSync(schemaFile, banner + source);
}

function functionQuery() {
  return `
    select coalesce(json_agg(f order by f.name), '[]') from (
      select p.proname as name,
             coalesce(p.proargnames, '{}') as "argNames",
             array(
               select format_type(t, null)
               from unnest(p.proargtypes::oid[]) with ordinality as u(t, i)
               order by i
             ) as "argTypes",
             p.pronargdefaults as defaults,
             format_type(p.prorettype, null) as returns,
             p.proargmodes is not null as "hasModes"
      from pg_proc p
      join pg_namespace n on n.oid = p.pronamespace
      where n.nspname = 'public'
        and p.prokind = 'f'
        and not p.proretset
        and p.prorettype <> 'trigger'::regtype
        and has_function_privilege('service_role', p.oid, 'EXECUTE')
    ) f`;
}

function generateFunctions(psql) {
  const functions = JSON.parse(psql(["-d", DATABASE, "-A", "-t", "-c", functionQuery()]));
  const registry = [];
  const argumentTypes = [];
  for (const fn of functions) {
    if (fn.hasModes) throw new Error(`${fn.name} declares OUT or INOUT arguments`);
    const firstDefault = fn.argTypes.length - fn.defaults;
    const args = fn.argTypes.map((type, index) => {
      const name = fn.argNames[index];
      const tsType = ARGUMENT_TYPES.get(type);
      if (!name) throw new Error(`${fn.name} has an unnamed argument`);
      if (!tsType) throw new Error(`${fn.name}.${name} has unmapped type ${type}`);
      return { name, type, tsType, optional: index >= firstDefault };
    });
    registry.push(
      `  ${fn.name}: { args: [${args.map((a) => `["${a.name}", "${a.type}"]`).join(", ")}], ` +
        `returns: "${fn.returns}" },`,
    );
    const members = args.map(
      (a) => ` readonly ${a.name}${a.optional ? "?" : ""}: ${a.tsType} | null;`,
    );
    argumentTypes.push(
      `  ${fn.name}: ${members.length === 0 ? "Readonly<Record<string, never>>" : `{${members.join("")} }`};`,
    );
  }
  writeFileSync(
    functionsFile,
    `${banner}import type { Json } from "@/lib/json";

/** Every function the service role may call with one result: argument names and SQL types. */
export const databaseFunctions = {
${registry.join("\n")}
} as const;

export type DatabaseFunctionName = keyof typeof databaseFunctions;

/** Named arguments per function. An optional argument falls back to its SQL default. */
export interface DatabaseFunctionArgs {
${argumentTypes.join("\n")}
}
`,
  );
  return functions.length;
}

const workDir = mkdtempSync(join(tmpdir(), "wgi-db-generate-"));
const dataDir = join(workDir, "data");
let started = false;
try {
  const port = await freePort();
  run("initdb", ["-D", dataDir, "-U", "postgres", "--auth=trust"]);
  run("pg_ctl", [
    "-D",
    dataDir,
    "-l",
    join(workDir, "postgres.log"),
    "-o",
    `-p ${port} -c listen_addresses=127.0.0.1 -c unix_socket_directories=''`,
    "-w",
    "start",
  ]);
  started = true;
  const psql = (args) =>
    run("psql", [
      "-h",
      "127.0.0.1",
      "-p",
      String(port),
      "-U",
      "postgres",
      "-X",
      "-q",
      ...args,
      "-v",
      "ON_ERROR_STOP=1",
    ]);
  const migrations = applyMigrations(psql);
  generateSchema(`postgresql://postgres@127.0.0.1:${port}/${DATABASE}`, workDir);
  const functions = generateFunctions(psql);
  run("npx", ["oxfmt", schemaFile, functionsFile], { cwd: root });
  console.log(
    `Applied ${migrations} migrations; wrote src/lib/db/schema.ts and ${functions} functions to src/lib/db/functions.ts`,
  );
} finally {
  if (started) run("pg_ctl", ["-D", dataDir, "-m", "fast", "-w", "stop"]);
  rmSync(workDir, { recursive: true, force: true });
}
