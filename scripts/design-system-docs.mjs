const STOCK_DIR = "src/components/stock/";
const CALL_SITE = /^src\/.*\.tsx$/;
const RESTYLES = 'design-system/styling.md "Recorded call-site restyles"';

/** The utility a class applies, without its variants, important mark or negative sign. */
function utilityOf(token) {
  let depth = 0;
  let start = 0;
  for (let index = 0; index < token.length; index += 1) {
    const char = token[index];
    if (char === "[" || char === "(") depth += 1;
    else if (char === "]" || char === ")") depth -= 1;
    else if (char === ":" && depth === 0) start = index + 1;
  }
  return token.slice(start).replace(/^!|!$/g, "").replace(/^-/, "");
}

/** Utilities that place text or collapse a table rather than paint it. */
const NOT_LOOK =
  /^(?:text-(?:left|center|right|justify|start|end|wrap|nowrap|balance|pretty|ellipsis|clip)$|border-(?:collapse|separate|spacing))/;

/** Utility prefixes that set type, paint, shape or motion; a trailing `$` matches a whole name. */
const LOOK_PREFIXES = [
  "text-|font-|leading-|tracking-|decoration-|underline|overline$|line-through$|no-underline$",
  "(?:upper|lower)case$|capitalize$|normal-case$|(?:not-)?italic$|(?:subpixel-)?antialiased$",
  "(?:tabular|oldstyle|lining|proportional|normal|slashed|diagonal|stacked)-(?:nums|zero|fractions)$",
  "bg-|from-|via-|to-|border|divide-|opacity-|fill-|stroke-|accent-|caret-|mix-blend-|mask-",
  "filter|backdrop-|blur|brightness-|contrast-|grayscale|hue-rotate-|invert|saturate-|sepia",
  "rounded|(?:inset-|drop-)?shadow|ring|outline|shimmer",
  "transition|duration-|ease-|delay-|animate-|scale-",
];
const LOOK = new RegExp(`^(?:${LOOK_PREFIXES.join("|")})`);

/** Whether a class sets a component's type, color, border, radius, shadow or motion. */
export function setsLook(token) {
  const utility = utilityOf(token);
  return !NOT_LOOK.test(utility) && LOOK.test(utility);
}

const EQUALITY = new Set([
  ts.SyntaxKind.EqualsEqualsEqualsToken,
  ts.SyntaxKind.ExclamationEqualsEqualsToken,
  ts.SyntaxKind.EqualsEqualsToken,
  ts.SyntaxKind.ExclamationEqualsToken,
]);

/** The literal strings in a `className` value, leaving out comparisons such as `open === "yes"`. */
function classStrings(node) {
  if (ts.isBinaryExpression(node) && EQUALITY.has(node.operatorToken.kind)) return [];
  if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) return [node.text];
  if (ts.isTemplateHead(node) || ts.isTemplateMiddle(node) || ts.isTemplateTail(node)) {
    return [node.text];
  }
  const found = [];
  ts.forEachChild(node, (child) => {
    found.push(...classStrings(child));
  });
  return found;
}

/** The words of every literal class string in a node. */
function classWords(node) {
  return classStrings(node).flatMap((text) => text.split(/\s+/).filter(Boolean));
}

/**
 * `{ name, label, offset, classes }` for each literal class list that dresses something from
 * ui/: a `className` on an element imported from it, the arguments composed beside a call to one
 * of its recipes, as in `cn(buttonVariants(), "w-full")`, and a recipe call's own `className`
 * option. `name` is the export, `label` the element or call as the file writes it, and `recipes`
 * holds each ui/ recipe as `path name`.
 */
function uiClassNames(path, source, fileSet, recipes) {
  const bindings = new Map();
  const namespaces = new Map();
  for (const declaration of importsOf(source)) {
    const target = resolveImport(path, declaration.specifier, fileSet);
    if (target === null || !target.startsWith(UI_DIR)) continue;
    for (const [index, local] of declaration.locals.entries()) {
      bindings.set(local, { target, name: declaration.names[index], written: local });
    }
    if (declaration.namespace !== null) namespaces.set(declaration.namespace, target);
  }
  const found = [];
  if (bindings.size === 0 && namespaces.size === 0) return found;
  const exportAt = (expression) => {
    if (ts.isIdentifier(expression)) return bindings.get(expression.text) ?? null;
    if (!ts.isPropertyAccessExpression(expression) || !ts.isIdentifier(expression.expression)) {
      return null;
    }
    const target = namespaces.get(expression.expression.text);
    if (target === undefined) return null;
    const written = `${expression.expression.text}.${expression.name.text}`;
    return { target, name: expression.name.text, written };
  };
  const recipeCalled = (node) => {
    const called = ts.isCallExpression(node) ? exportAt(node.expression) : null;
    return called !== null && recipes.has(`${called.target} ${called.name}`) ? called : null;
  };
  const add = (name, label, node, classes) => {
    found.push({ name, label, offset: node.getStart(source), classes });
  };
  const visit = (node) => {
    const element =
      ts.isJsxOpeningElement(node) || ts.isJsxSelfClosingElement(node)
        ? exportAt(node.tagName)
        : null;
    for (const attribute of element === null ? [] : node.attributes.properties) {
      const isClassName =
        ts.isJsxAttribute(attribute) &&
        ts.isIdentifier(attribute.name) &&
        attribute.name.text === "className" &&
        attribute.initializer !== undefined;
      if (isClassName) {
        add(element.name, `<${element.written}>`, node, classWords(attribute.initializer));
      }
    }
    const recipe = recipeCalled(node);
    for (const option of recipe === null ? [] : objectProperties(node.arguments[0])) {
      if (["className", "class"].includes(propertyName(option.name))) {
        add(recipe.name, `${recipe.written}()`, node, classWords(option.initializer));
      }
    }
    for (const argument of ts.isCallExpression(node) ? node.arguments : []) {
      const composed = recipeCalled(argument);
      if (composed === null) continue;
      const beside = node.arguments.filter((other) => recipeCalled(other) === null);
      add(composed.name, `${composed.written}()`, argument, beside.flatMap(classWords));
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
  return found;
}

/**
 * A call site gives a ui/ component layout, never a look. Each class that sets the look of a
 * ui/ element or recipe call outside ui/ and stock/ is either recorded, by file and component,
 * in a guide's table with "Component", "Classes" and "Call sites" columns, or a problem; so is a
 * recorded class the file no longer sets on that component.
 */
function checkRestyles(repo, context, uiModules, problems) {
  const recipes = new Set(
    uiModules.flatMap((entry) => entry.recipes.map((recipe) => `${entry.path} ${recipe.name}`)),
  );
  const recorded = new Map();
  for (const doc of docsSet(repo.files)) {
    for (const row of restyleRows(repo.read(doc))) {
      const report = (message) => problems.push({ file: doc, line: row.line, message });
      const names = [...row.component.matchAll(/`([A-Za-z_]\w*)`/g)].map((match) => match[1]);
      const classes = [...row.classes.matchAll(/`([^`]+)`/g)].map((match) => match[1]);
      const entries = citedEntries(doc, row.sites);
      if (names.length === 0) report("restyle row names no backticked component");
      if (classes.length === 0) report("restyle row names no backticked class");
      if (entries.length === 0) report("restyle row names no call site");
      for (const token of classes.filter((candidate) => !setsLook(candidate))) {
        report(`\`${token}\` sets no look; a call site's layout needs no record`);
      }
      for (const entry of entries) {
        const { path, problem } = resolveCited(entry, context);
        if (path === undefined) {
          report(`call site ${entry} ${problem}`);
          continue;
        }
        for (const name of names) {
          for (const token of classes.filter(setsLook)) {
            const key = `${path} ${name} ${token}`;
            const earlier = recorded.get(key);
            if (earlier === undefined) {
              recorded.set(key, { doc, line: row.line, path, name, token, seen: false });
            } else {
              const at = `${earlier.doc}:${earlier.line}`;
              report(`\`${token}\` on ${name} at ${path} is already recorded at ${at}`);
            }
          }
        }
      }
    }
  }
  for (const path of repo.files) {
    if (!CALL_SITE.test(path) || path.startsWith(UI_DIR) || path.startsWith(STOCK_DIR)) continue;
    const text = repo.read(path);
    for (const use of uiClassNames(path, context.parse(path), context.fileSet, recipes)) {
      const unrecorded = [];
      for (const token of use.classes.filter(setsLook)) {
        const record = recorded.get(`${path} ${use.name} ${token}`);
        if (record === undefined) unrecorded.push(`\`${token}\``);
        else record.seen = true;
      }
      if (unrecorded.length === 0) continue;
      problems.push({
        file: path,
        line: lineAt(text, use.offset),
        message: `sets the look of ${use.label} with ${unrecorded.join(", ")}; move it into a recipe or record it in ${RESTYLES}`,
      });
    }
  }
  for (const { doc, line, path, name, token, seen } of recorded.values()) {
    if (!seen) {
      problems.push({ file: doc, line, message: `${path} no longer sets \`${token}\` on ${name}` });
    }
  }
}

/**
 * Registry source in stock/ is bundle input, not approved design: each import of it from outside
 * stock/ is an exception a guide's "Real uses" table records, in a row naming the component.
 */
function checkStockImports(repo, context, problems) {
  const recorded = new Set();
  for (const doc of docsSet(repo.files)) {
    for (const row of realUseRows(repo.read(doc))) {
      const names = [...row.component.matchAll(/`([A-Za-z_]\w*)`/g)].map((match) => match[1]);
      for (const entry of citedEntries(doc, row.uses)) {
        const { path } = resolveCited(entry, context);
        if (path === undefined) continue;
        for (const name of names) recorded.add(`${path} ${name}`);
      }
    }
  }
  for (const path of repo.files) {
    if (!SOURCE_FILE.test(path) || path.startsWith(STOCK_DIR)) continue;
    for (const declaration of importsOf(context.parse(path))) {
      const target = resolveImport(path, declaration.specifier, context.fileSet);
      if (target === null || !target.startsWith(STOCK_DIR)) continue;
      const unrecorded = declaration.names.filter((name) => !recorded.has(`${path} ${name}`));
      if (declaration.namespace !== null) unrecorded.push(`* as ${declaration.namespace}`);
      if (unrecorded.length === 0) continue;
      problems.push({
        file: path,
        line: lineAt(repo.read(path), declaration.start),
        message: `imports ${unrecorded.join(", ")} from ${target}, which no guide's Real uses table records; adopt it into ui/ or record the exception`,
      });
    }
  }
}

/* ----------------------------------------------------------------- inventory */

function stringValue(node) {
  if (
    node !== undefined &&
    (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node))
  ) {
    return node.text;
  }
  return null;
}

function propertyName(node) {
  if (node !== undefined && (ts.isIdentifier(node) || ts.isStringLiteral(node))) return node.text;
  return null;
}

function objectProperties(node) {
  if (node === undefined || !ts.isObjectLiteralExpression(node)) return [];
  return node.properties.filter((property) => ts.isPropertyAssignment(property));
}

/** `const name = cva(base, { variants, defaultVariants })` as `{ name, axes }`. */
function recipesIn(source) {
  const found = [];
  for (const statement of source.statements) {
    if (!ts.isVariableStatement(statement)) continue;
    for (const declaration of statement.declarationList.declarations) {
      const call = declaration.initializer;
      const isCva =
        call !== undefined &&
        ts.isCallExpression(call) &&
        ts.isIdentifier(call.expression) &&
        call.expression.text === "cva";
      if (!isCva || !ts.isIdentifier(declaration.name)) continue;
      const config = objectProperties(call.arguments[1]);
      const option = (key) => config.find((property) => propertyName(property.name) === key);
      const defaults = new Map(
        objectProperties(option("defaultVariants")?.initializer).map((property) => [
          propertyName(property.name),
          stringValue(property.initializer),
        ]),
      );
      const axes = objectProperties(option("variants")?.initializer).map((axis) => {
        const name = propertyName(axis.name);
        const values = objectProperties(axis.initializer)
          .map((value) => propertyName(value.name))
          .filter((value) => value !== null);
        return { name, values, fallback: defaults.get(name) ?? null };
      });
      found.push({ name: declaration.name.text, axes });
    }
  }
  return found;
}

function unionValues(type) {
  if (type === undefined) return null;
  const members = ts.isUnionTypeNode(type) ? type.types : [type];
  const values = members.map((member) =>
    ts.isLiteralTypeNode(member) && ts.isStringLiteral(member.literal) ? member.literal.text : null,
  );
  return values.every((value) => value !== null) ? values : null;
}

/**
 * The appearance axes a props type declares: `VariantProps<typeof recipe>` members, string-literal
 * union properties, and local aliases or interfaces built from them, seen through `Readonly<>`. An
 * axis is required when a property signature names it without `?`.
 */
function propAxes(type, recipesByName, locals) {
  const axes = new Map();
  const optional = new Map();
  const add = (name, values, fallback = null) => {
    if (!axes.has(name)) axes.set(name, { name, values, fallback, required: false });
  };
  const members = (list) => {
    for (const member of list) {
      const name = ts.isPropertySignature(member) ? propertyName(member.name) : null;
      if (name === null) continue;
      const values = unionValues(member.type);
      if (values !== null) add(name, values);
      optional.set(name, member.questionToken !== undefined);
    }
  };
  const walk = (node) => {
    if (node === undefined) return;
    if (ts.isIntersectionTypeNode(node)) {
      for (const part of node.types) walk(part);
    } else if (ts.isParenthesizedTypeNode(node)) walk(node.type);
    else if (ts.isTypeLiteralNode(node)) members(node.members);
    else if (ts.isTypeReferenceNode(node) || ts.isExpressionWithTypeArguments(node)) {
      const target = ts.isTypeReferenceNode(node) ? node.typeName : node.expression;
      const name = ts.isIdentifier(target) ? target.text : null;
      const [argument] = node.typeArguments ?? [];
      if (name === "VariantProps" && argument !== undefined && ts.isTypeQueryNode(argument)) {
        const recipeName = ts.isIdentifier(argument.exprName) ? argument.exprName.text : null;
        for (const axis of recipesByName.get(recipeName)?.axes ?? []) {
          add(axis.name, axis.values, axis.fallback);
        }
      } else if (name === "Readonly" && argument !== undefined) walk(argument);
      else if (name !== null && locals.has(name)) {
        const local = locals.get(name);
        if (ts.isTypeAliasDeclaration(local)) walk(local.type);
        else {
          for (const clause of local.heritageClauses ?? []) {
            for (const part of clause.types) walk(part);
          }
          members(local.members);
        }
      }
    }
  };
  walk(type);
  for (const axis of axes.values()) axis.required = optional.get(axis.name) === false;
  return [...axes.values()];
}

function functionOf(statement) {
  if (ts.isFunctionDeclaration(statement) && statement.name !== undefined) {
    return { name: statement.name.text, fn: statement };
  }
  if (!ts.isVariableStatement(statement)) return null;
  const [declaration] = statement.declarationList.declarations;
  const init = declaration?.initializer;
  const isFunction =
    init !== undefined && (ts.isArrowFunction(init) || ts.isFunctionExpression(init));
  return isFunction && ts.isIdentifier(declaration.name)
    ? { name: declaration.name.text, fn: init }
    : null;
}

/** Destructured string defaults win over the recipe's defaultVariants. */
function componentAxes(fn, recipesByName, locals) {
  const [props] = fn.parameters;
  const axes = propAxes(props?.type, recipesByName, locals);
  if (props === undefined || !ts.isObjectBindingPattern(props.name)) return axes;
  for (const element of props.name.elements) {
    const name = propertyName(element.propertyName ?? element.name);
    const value = stringValue(element.initializer);
    if (name === null || value === null) continue;
    const axis = axes.find((candidate) => candidate.name === name);
    if (axis !== undefined) axis.fallback = value;
    else if (CHECKED_AXES.has(name)) {
      axes.push({ name, values: [], fallback: value, required: false });
    }
  }
  return axes;
}

const NOT_BUILT_ON = new Set(["react", "cn", "class-variance-authority", "lucide-react"]);
const COMPONENT_NAME = /^[A-Z]\w*[a-z]\w*$/;

function inventoryModule(path, source, recipesByName) {
  const locals = new Map();
  const functions = new Map();
  for (const statement of source.statements) {
    if (ts.isTypeAliasDeclaration(statement) || ts.isInterfaceDeclaration(statement)) {
      locals.set(statement.name.text, statement);
    }
    const found = functionOf(statement);
    if (found !== null) functions.set(found.name, found.fn);
  }
  const [first] = source.statements;
  const builtOn = source.statements
    .filter((statement) => ts.isImportDeclaration(statement))
    .filter((statement) => statement.importClause?.isTypeOnly !== true)
    .map((statement) => stringValue(statement.moduleSpecifier))
    .filter(
      (specifier) =>
        specifier !== null &&
        !specifier.startsWith(".") &&
        !specifier.startsWith("@/") &&
        !NOT_BUILT_ON.has(specifier),
    );
  const entry = {
    path,
    useClient:
      first !== undefined &&
      ts.isExpressionStatement(first) &&
      ts.isStringLiteral(first.expression) &&
      first.expression.text === "use client",
    builtOn: [...new Set(builtOn)],
    components: [],
    recipes: [],
    helpers: [],
    types: [],
  };
  for (const exported of exportsOf(source)) {
    const fn = functions.get(exported.local);
    if (exported.typeOnly || locals.has(exported.local)) entry.types.push(exported.name);
    else if (recipesByName.has(exported.local)) {
      entry.recipes.push({ name: exported.name, axes: recipesByName.get(exported.local).axes });
    } else if (COMPONENT_NAME.test(exported.name)) {
      const axes = fn === undefined ? [] : componentAxes(fn, recipesByName, locals);
      entry.components.push({ name: exported.name, axes });
    } else entry.helpers.push(exported.name);
  }
  return entry;
}

/** The shared component library in src/components/ui/, parsed module by module. */
export function inventory(repo, parse = parserFor(repo)) {
  const paths = repo.files.filter(
    (path) =>
      path.startsWith(UI_DIR) && /\.(ts|tsx)$/.test(path) && !/\.(test|spec|d)\.tsx?$/.test(path),
  );
  const recipesByName = new Map();
  for (const path of paths) {
    for (const recipe of recipesIn(parse(path))) recipesByName.set(recipe.name, recipe);
  }
  return paths.map((path) => inventoryModule(path, parse(path), recipesByName));
}

function renderAxis(axis) {
  const values = axis.values.map((value) =>
    value === axis.fallback && !axis.required ? `**\`${value}\`**` : `\`${value}\``,
  );
  if (axis.values.length === 0 && axis.fallback !== null) values.push(`**\`${axis.fallback}\`**`);
  return `\`${axis.name}\`${axis.required ? " (required)" : ""} ${values.join(" · ")}`;
}

const listNames = (names) => names.map((name) => `\`${name}\``).join(", ");

/** The generated inventory block, markers included. */
export function renderInventory(uiModules) {
  const lines = [BEGIN, "", "Bold marks the default; a required prop has none.", ""];
  for (const entry of uiModules) {
    const facts = [`[\`${posix.basename(entry.path)}\`](../${entry.path})`];
    if (entry.useClient) facts.push('`"use client"`');
    if (entry.builtOn.length > 0) facts.push(`built on ${listNames(entry.builtOn)}`);
    lines.push(`- ${facts.join(" · ")}`);
    const plain = entry.components.filter((component) => component.axes.length === 0);
    for (const component of entry.components) {
      if (component.axes.length > 0) {
        lines.push(`  - \`${component.name}\`: ${component.axes.map(renderAxis).join("; ")}`);
      }
    }
    if (plain.length > 0) {
      const label = plain.length === entry.components.length ? "Components" : "Also exports";
      lines.push(`  - ${label}: ${listNames(plain.map((component) => component.name))}`);
    }
    if (entry.recipes.length > 0) {
      lines.push(`  - Recipes: ${listNames(entry.recipes.map((recipe) => recipe.name))}`);
    }
    const others = [...entry.helpers, ...entry.types];
    if (others.length > 0) lines.push(`  - Helpers and types: ${listNames(others)}`);
  }
  lines.push("", END);
  return lines.join("\n");
}

function generatedBlock(text) {
  const begin = text.indexOf(BEGIN);
  const end = text.indexOf(END);
  if (begin === -1 || end === -1 || end < begin) return null;
  return { begin, end: end + END.length, block: text.slice(begin, end + END.length) };
}

function checkInventory(repo, context, uiModules, problems) {
  if (!context.fileSet.has(INVENTORY)) {
    problems.push({ file: INVENTORY, line: 1, message: "missing; create it with the markers" });
    return;
  }
  const text = repo.read(INVENTORY);
  const current = generatedBlock(text);
  if (current === null) {
    problems.push({ file: INVENTORY, line: 1, message: "generated block markers are missing" });
  } else if (current.block !== renderInventory(uiModules)) {
    const message = "component inventory is stale; run npm run design-system:write";
    problems.push({ file: INVENTORY, line: lineAt(text, current.begin), message });
  }
}

/* ---------------------------------------------------------- index and budgets */

function checkIndexAndBudgets(repo, problems) {
  const docs = docsSet(repo.files);
  if (!docs.includes(ROOT_GUIDE)) return;
  const linked = new Set(
    linkDestinations(markdownParts(repo.read(ROOT_GUIDE)).prose).map(
      ({ destination }) => resolveDestination(ROOT_GUIDE, destination)?.path,
    ),
  );
  for (const path of docs) {
    if (path !== ROOT_GUIDE && !linked.has(path)) {
      problems.push({ file: ROOT_GUIDE, line: 1, message: `does not link the guide ${path}` });
    }
    if (path === INVENTORY) continue;
    const lines = repo.read(path).replace(/\n$/, "").split("\n").length;
    const budget = path === ROOT_GUIDE ? ROOT_BUDGET : GUIDE_BUDGET;
    if (lines >= budget) {
      problems.push({
        file: path,
        line: lines,
        message: `${lines} lines; keep it under ${budget}`,
      });
    }
  }
}

/* --------------------------------------------------------------------- check */

/** Every drift problem as `{ file, line, message }`, sorted by file and line. */
export function checkRepo(repo) {
  const context = {
    files: repo.files,
    fileSet: new Set(repo.files),
    dirs: directoriesOf(repo.files),
    topLevel: new Set(repo.files.map((path) => path.split("/")[0])),
    basenames: new Set(repo.files.map((path) => posix.basename(path))),
    localOnly: localOnlyPaths(repo),
    parse: parserFor(repo),
  };
  const problems = [];
  const uiModules = inventory(repo, context.parse);
  checkLinks(repo, context, problems);
  checkCitations(repo, context, problems);
  checkPathsAndNames(repo, context, problems);
  checkCommentPaths(repo, context, problems);
  checkExamples(repo, uiModules, problems);
  checkRealUses(repo, context, problems);
  checkRestyles(repo, context, uiModules, problems);
  checkStockImports(repo, context, problems);
  if (docsSet(repo.files).some((path) => path !== ROOT_GUIDE)) {
    checkInventory(repo, context, uiModules, problems);
  }
  checkIndexAndBudgets(repo, problems);
  return problems.toSorted((a, b) => a.file.localeCompare(b.file) || a.line - b.line);
}

