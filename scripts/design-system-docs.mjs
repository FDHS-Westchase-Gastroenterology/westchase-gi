/** A comment-free CSS tree of `{ prelude, line, declarations, children }` nodes. */
export function parseCss(css) {
  const text = css.replace(/\/\*[\s\S]*?\*\//g, (comment) => comment.replace(/[^\n]/g, " "));
  const root = { prelude: "", line: 1, declarations: [], children: [] };
  const stack = [root];
  let buffer = "";
  let bufferLine = 0;
  let line = 1;
  let quote = "";
  let parens = 0;
  const take = (char) => {
    if (bufferLine === 0 && /\S/.test(char)) bufferLine = line;
    buffer += char;
  };
  const settle = (node) => {
    const statement = buffer.trim();
    const colon = statement.indexOf(":");
    if (colon > 0 && !statement.startsWith("@")) {
      node.declarations.push({
        property: statement.slice(0, colon).trim().toLowerCase(),
        value: statement.slice(colon + 1).trim(),
        line: bufferLine,
      });
    }
    buffer = "";
    bufferLine = 0;
  };
  for (let index = 0; index < text.length; index += 1) {
    const char = text[index];
    if (char === "\n") line += 1;
    if (quote !== "") {
      if (char === quote && text[index - 1] !== "\\") quote = "";
      take(char);
    } else if (char === '"' || char === "'") {
      quote = char;
      take(char);
    } else if (char === "(" || char === ")") {
      parens = Math.max(0, parens + (char === "(" ? 1 : -1));
      take(char);
    } else if (parens > 0 || (char !== "{" && char !== "}" && char !== ";")) {
      take(char);
    } else if (char === "{") {
      const node = {
        prelude: buffer.trim(),
        line: bufferLine || line,
        declarations: [],
        children: [],
      };
      stack.at(-1).children.push(node);
      stack.push(node);
      buffer = "";
      bufferLine = 0;
    } else {
      settle(stack.at(-1));
      if (char === "}" && stack.length > 1) stack.pop();
    }
  }
  return root;
}

const KEYFRAMES = /^@(?:-\w+-)?keyframes\b/;
const SPACING = /^(?:(?:margin|padding)(?:-.+)?|gap|row-gap|column-gap)$/;
const COLOR_FUNCTION = /\b(?:rgba?|hsla?|oklch|oklab|lab|lch|hwb|color)\(/g;
const HEX = /#[0-9a-f]{3,8}\b/gi;
const NAMED_COLOR = /(?<![\w-])(?:white|black)(?![\w-])/g;
const RADIUS = /^border(?:-[a-z]+)*-radius$/;
const PILL = /^(?:9{3,}px|50%)$/;
const EASING =
  /\b(?:cubic-bezier|steps)\(|(?<![\w-])(?:linear|ease|ease-in|ease-out|ease-in-out|step-start|step-end)(?![\w-])/;

/** The value with every call of the named CSS function removed, nesting included. */
function withoutFunction(value, name) {
  const opener = new RegExp(`(?<![\\w-])${name}\\(`, "g");
  let out = "";
  let cursor = 0;
  for (let match = opener.exec(value); match !== null; match = opener.exec(value)) {
    if (match.index < cursor) continue;
    out += value.slice(cursor, match.index);
    let depth = 0;
    let end = match.index + match[0].length - 1;
    for (; end < value.length; end += 1) {
      if (value[end] === "(") depth += 1;
      else if (value[end] === ")") {
        depth -= 1;
        if (depth === 0) break;
      }
    }
    cursor = end + 1;
  }
  return out + value.slice(cursor);
}

function hasLiteral(value, unit) {
  const literal = new RegExp(`(?<![\\w.-])-?(\\d*\\.?\\d+)${unit}\\b`, "g");
  return [...value.matchAll(literal)].some((match) => Number(match[1]) !== 0);
}

function hasLength(value) {
  return ["rem", "px", "pt", "em"].some((unit) => hasLiteral(value, unit));
}

/** Splits a value on commas outside parentheses, such as the layers of a box-shadow. */
function layersOf(value) {
  const layers = [];
  let depth = 0;
  let current = "";
  for (const char of value) {
    if (char === "(") depth += 1;
    if (char === ")") depth -= 1;
    if (char === "," && depth === 0) {
      layers.push(current.trim());
      current = "";
    } else current += char;
  }
  return [...layers, current.trim()].filter((layer) => layer !== "");
}

const varsOf = (value) => [...value.matchAll(/var\(\s*(--[\w-]+)/g)].map((match) => match[1]);

function radiusKind(value) {
  const bare = withoutFunction(value, "var");
  const vars = varsOf(value);
  if (PILL.test(value)) return "pill";
  if (hasLength(bare)) return "literal";
  if (vars.length > 0 && vars.every((name) => name.startsWith("--radius"))) return "token";
  if (vars.length > 0) return "otherVar";
  return "zero";
}

function shadowKind(value) {
  if (value === "none") return "none";
  const raised = layersOf(value).filter((layer) => !/^inset\b/.test(layer));
  if (raised.length === 0) return "insetOnly";
  const varOnly = raised.every((layer) => withoutFunction(layer, "var").trim() === "");
  if (!varOnly) return "literal";
  const names = raised.flatMap(varsOf);
  return names.every((name) => name.startsWith("--shadow-")) ? "token" : "otherVar";
}

function walkCss(node, visit, inKeyframes = false) {
  const keyframes = inKeyframes || KEYFRAMES.test(node.prelude);
  for (const declaration of node.declarations) visit(declaration, keyframes);
  for (const child of node.children) walkCss(child, visit, keyframes);
}

/**
 * Declaration counts by whether they read a token. Spacing (margin, padding, gap) is literal rem
 * when any nonzero rem literal sits outside var(), else literal px, else `--ps-*` only, else
 * another var, else other (0, auto, percentages). Font sizes read `--pt-*`, another var, or a
 * literal. Colors count occurrences: literal functions and hex outside color-mix(), white and
 * black, color-mix() calls, and literals inside custom-property definitions. Motion counts
 * transition and animation declarations outside @keyframes with a nonzero literal duration, a
 * literal easing, or only tokens. Radii are a nonzero length literal, a pill (999px or 50%), only
 * `--radius*` tokens, another var, or zero. Box shadows are none, inset only (a drawn line, not
 * elevation), or by what their raised layers read: only `--shadow-*` tokens, another var, or a
 * literal.
 */
export function measureCss(css) {
  const counts = {
    spacing: { total: 0, rem: 0, px: 0, psOnly: 0, otherVar: 0, other: 0 },
    fontSize: { total: 0, pt: 0, otherVar: 0, literal: 0 },
    color: { literal: 0, named: 0, colorMix: 0, inCustomProperties: 0 },
    motion: { total: 0, literalDuration: 0, literalEasing: 0, tokenOnly: 0 },
    radius: { total: 0, token: 0, pill: 0, otherVar: 0, literal: 0, zero: 0 },
    shadow: { total: 0, token: 0, otherVar: 0, literal: 0, insetOnly: 0, none: 0 },
  };
  walkCss(parseCss(css), ({ property, value }, inKeyframes) => {
    const unmixed = withoutFunction(value, "color-mix");
    const colorLiterals =
      (unmixed.match(COLOR_FUNCTION)?.length ?? 0) + (unmixed.match(HEX)?.length ?? 0);
    if (property.startsWith("--")) {
      counts.color.inCustomProperties += colorLiterals;
      return;
    }
    counts.color.literal += colorLiterals;
    counts.color.colorMix += value.match(/\bcolor-mix\(/g)?.length ?? 0;
    counts.color.named += unmixed.match(NAMED_COLOR)?.length ?? 0;
    const bare = withoutFunction(value, "var");
    const vars = [...value.matchAll(/var\(\s*(--[\w-]+)/g)].map((match) => match[1]);
    if (SPACING.test(property)) {
      counts.spacing.total += 1;
      if (hasLiteral(bare, "rem")) counts.spacing.rem += 1;
      else if (hasLiteral(bare, "px")) counts.spacing.px += 1;
      else if (vars.length > 0 && vars.every((name) => name.startsWith("--ps-"))) {
        counts.spacing.psOnly += 1;
      } else if (vars.length > 0) counts.spacing.otherVar += 1;
      else counts.spacing.other += 1;
    }
    const important = value.replace(/\s*!important$/, "").trim();
    if (RADIUS.test(property)) {
      counts.radius.total += 1;
      counts.radius[radiusKind(important)] += 1;
    }
    if (property === "box-shadow") {
      counts.shadow.total += 1;
      counts.shadow[shadowKind(important)] += 1;
    }
    if (property === "font-size") {
      counts.fontSize.total += 1;
      if (vars.some((name) => name.startsWith("--pt-"))) counts.fontSize.pt += 1;
      else if (vars.length > 0) counts.fontSize.otherVar += 1;
      else counts.fontSize.literal += 1;
    }
    if (!inKeyframes && /^(?:transition|animation)(?:-.+)?$/.test(property)) {
      counts.motion.total += 1;
      const duration = hasLiteral(bare, "m?s");
      const easing = EASING.test(bare);
      if (duration) counts.motion.literalDuration += 1;
      if (easing) counts.motion.literalEasing += 1;
      if (!duration && !easing && vars.length > 0) counts.motion.tokenOnly += 1;
    }
  });
  return counts;
}

function cssRules(css) {
  const rules = [];
  const visit = (node, inKeyframes) => {
    const keyframes = inKeyframes || KEYFRAMES.test(node.prelude);
    if (!keyframes && node.prelude !== "" && !node.prelude.startsWith("@")) {
      rules.push({
        prelude: node.prelude,
        line: node.line,
        declarations: node.declarations.length,
      });
    }
    for (const child of node.children) visit(child, keyframes);
  };
  visit(parseCss(css), false);
  return rules;
}

function topLevelSelectors(prelude) {
  const parts = [];
  let depth = 0;
  let current = "";
  for (const char of prelude) {
    if (char === "(" || char === "[") depth += 1;
    if (char === ")" || char === "]") depth -= 1;
    if (char === "," && depth === 0) {
      parts.push(current.trim());
      current = "";
    } else current += char;
  }
  return [...parts, current.trim()].filter((part) => part !== "");
}

function classesIn(selector) {
  return [...selector.matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)].map((match) => match[1]);
}

/**
 * Rules whose every selector names a class that no source token mentions and no dynamic prefix
 * builds (a token ending in "-" with two or more segments, such as `wgi-state-`). These are
 * candidates to verify by hand, not a list to delete.
 */
export function unreferencedRules(css, tokens) {
  const prefixes = [...tokens].filter(
    (token) => token.endsWith("-") && token.split("-").length > 2,
  );
  const referenced = (name) =>
    tokens.has(name) || prefixes.some((prefix) => name.startsWith(prefix));
  return cssRules(css).filter((rule) => {
    const selectors = topLevelSelectors(rule.prelude);
    return (
      selectors.length > 0 &&
      selectors.every((selector) => classesIn(selector).some((name) => !referenced(name)))
    );
  });
}

function sourceTokens(repo) {
  const tokens = new Set();
  for (const path of repo.files) {
    if (!/^src\/.*\.(ts|tsx|js|jsx|mjs|json|mdx|html)$/.test(path)) continue;
    for (const match of repo.read(path).matchAll(/[A-Za-z_][\w-]*/g)) tokens.add(match[0]);
  }
  return tokens;
}

function classPrefixes(css) {
  const counts = new Map();
  for (const rule of cssRules(css)) {
    for (const name of new Set(classesIn(rule.prelude))) {
      const prefix = name.split("-").slice(0, 2).join("-");
      counts.set(prefix, (counts.get(prefix) ?? 0) + 1);
    }
  }
  return [...counts].toSorted((a, b) => b[1] - a[1]).slice(0, 15);
}

function cssReport(root, paths) {
  const repo = loadRepo(root);
  const head = git(["rev-parse", "HEAD"], root).trim();
  const dirty = git(["status", "--porcelain", "--", ...paths], root).trim() !== "";
  const tokens = sourceTokens(repo);
  const lines = [`Source: ${head}${dirty ? " plus uncommitted changes to these files" : ""}`, ""];
  for (const path of paths) {
    const css = readFileSync(join(root, path), "utf8");
    const { spacing, fontSize, color, motion, radius, shadow } = measureCss(css);
    const prefixes = classPrefixes(css).map(([prefix, count]) => `${prefix} ${count}`);
    const dead = unreferencedRules(css, tokens);
    lines.push(
      path,
      `  spacing: ${spacing.total}; literal rem ${spacing.rem}, literal px ${spacing.px}, --ps-* only ${spacing.psOnly}, other var ${spacing.otherVar}, other ${spacing.other}`,
      `  font-size: ${fontSize.total}; --pt-* ${fontSize.pt}, other var ${fontSize.otherVar}, literal ${fontSize.literal}`,
      `  color: literal ${color.literal}, white/black ${color.named}, color-mix() ${color.colorMix}, literals in custom properties ${color.inCustomProperties}`,
      `  transition/animation: ${motion.total}; literal duration ${motion.literalDuration}, literal easing ${motion.literalEasing}, token-only ${motion.tokenOnly}`,
      `  border-radius: ${radius.total}; --radius* only ${radius.token}, pill ${radius.pill}, other var ${radius.otherVar}, literal ${radius.literal}, zero ${radius.zero}`,
      `  box-shadow: ${shadow.total}; --shadow-* only ${shadow.token}, other var ${shadow.otherVar}, literal ${shadow.literal}, inset only ${shadow.insetOnly}, none ${shadow.none}`,
      `  rules by class prefix: ${prefixes.join(", ")}`,
      `  rules naming a class no source file mentions: ${dead.length}`,
      ...dead.map((rule) => {
        const selector = rule.prelude.replace(/\s+/g, " ").slice(0, 110);
        return `    ${path}:${rule.line}  ${selector} (${rule.declarations} declarations)`;
      }),
      "",
    );
  }
  return lines.join("\n");
}

/* ---------------------------------------------------------------------- main */

export function main(argv, root = repoRoot) {
  const [mode = "check", ...rest] = argv.slice(2);
  if (mode === "check") {
    const problems = checkRepo(loadRepo(root));
    for (const { file, line, message } of problems) console.error(`${file}:${line}  ${message}`);
    if (problems.length > 0) {
      console.error(`\ndesign-system docs: ${problems.length} problem(s)\n`);
      return 1;
    }
    console.log("design-system docs: links, citations, names, examples and inventory agree");
    return 0;
  }
  if (mode === "write") {
    const repo = loadRepo(root);
    const text = repo.files.includes(INVENTORY) ? repo.read(INVENTORY) : "";
    const current = generatedBlock(text);
    if (current === null) throw new Error(`${INVENTORY} needs the ${BEGIN} and ${END} markers`);
    const block = renderInventory(inventory(repo));
    writeFileSync(
      join(root, INVENTORY),
      text.slice(0, current.begin) + block + text.slice(current.end),
    );
    console.log(`design-system docs: wrote the component inventory in ${INVENTORY}`);
    return 0;
  }
  if (mode === "css" && rest.length > 0) {
    console.log(cssReport(root, rest));
    return 0;
  }
  console.error(`unknown mode "${[mode, ...rest].join(" ")}". Use: check | write | css <file>...`);
  return 2;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  try {
    process.exit(main(process.argv));
  } catch (err) {
    console.error(`\ndesign-system docs ERROR: ${err.message}\n`);
    process.exit(2);
  }
}
