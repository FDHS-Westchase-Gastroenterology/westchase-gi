#!/usr/bin/env node
/**
 * Keeps DESIGN.md, the design-system/ guides, and the code telling one story.
 *
 *   npm run design-system:check    fail on any drift listed below
 *   npm run design-system:write    regenerate the component block in design-system/inventory.md
 *   node scripts/design-system-docs.mjs css <file>...
 *                                  measure stylesheets for the roadmap, stamped with HEAD
 *
 * `check` fails when:
 *   - a relative link in DESIGN.md or a guide, or a link from any other Markdown file into them,
 *     names a missing file or a missing heading anchor;
 *   - a citation such as DESIGN.md "Motion" or design-system/motion.md "Reduced motion", in
 *     Markdown, TypeScript, JavaScript or CSS, names a heading or bold lead-in the file lacks;
 *   - a backticked repository path in DESIGN.md or a guide names no file or directory;
 *   - a comment in src/ names a tracked repository path the checkout lacks;
 *   - a backticked PascalCase name in DESIGN.md or a guide is not an identifier in src/;
 *   - an example sets `variant`, `size`, `motion` or `orientation` to a value the component or
 *     recipe does not define;
 *   - a "Real uses" table cites a file that does not import the component its row names;
 *   - a call site outside src/components/ui/ and src/components/stock/ sets a ui/ component's
 *     type, color, border, radius, shadow or motion, in a `className` on its element or in a
 *     class composed beside a recipe call such as buttonVariants(), and no guide's call-site
 *     restyles table records it, or a row records a class its call site no longer sets;
 *   - a file outside src/components/stock/ imports from it, and no "Real uses" row names that
 *     import;
 *   - the generated block in design-system/inventory.md differs from src/components/ui/;
 *   - a guide is missing from DESIGN.md's links, or a file outgrows its line budget
 *     (DESIGN.md under 100 lines, each guide under 150; the inventory is exempt).
 *
 * Writing conventions the check relies on:
 *   - Write a name that does not exist in src/ (a retired component, an unadopted registry part,
 *     a product such as Next.js) without backticks.
 *   - Put a misuse example in a fence whose info string contains `incorrect` or `avoid`.
 *   - Write a local-only path with its directory, such as ds-bundle/_ds_sync.json, so the check
 *     can tell it from a missing tracked file (local-only-paths.json lists them).
 *   - Link a source line as `file.tsx#L12`; `file.tsx:12` is not a link GitHub resolves.
 *   - Give a call-site restyles table "Component", "Classes" and "Call sites" columns. A table
 *     cell cites a file by a link, a backticked path, or a backticked file name only one tracked
 *     file has, such as `auth-card.tsx`.
 */

