/* ---------------------------------------------------------------------- repo */

function git(args, root) {
  const run = spawnSync("git", args, { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
  if (run.status !== 0) throw new Error(`git ${args.join(" ")} failed: ${run.stderr.trim()}`);
  return run.stdout;
}

/**
 * Tracked files plus untracked files git does not ignore, as long as they exist on disk, with a
 * cached reader. Tests build the same `{ files, read }` pair in memory.
 */
export function loadRepo(root = repoRoot) {
  const listed = git(["ls-files", "-z", "--cached", "--others", "--exclude-standard"], root)
    .split("\0")
    .filter((path) => path !== "" && !path.startsWith(".claude/worktrees/"));
  const files = [...new Set(listed)].filter((path) => existsSync(join(root, path))).toSorted();
  const cache = new Map();
  const read = (path) => {
    if (!cache.has(path)) cache.set(path, readFileSync(join(root, path), "utf8"));
    return cache.get(path);
  };
  return { files, read };
}

/** DESIGN.md and every Markdown file directly under design-system/. */
export function docsSet(files) {
  return files.filter(
    (path) =>
      path === ROOT_GUIDE ||
      (path.startsWith(`${DOCS_DIR}/`) &&
        path.endsWith(".md") &&
        !path.slice(DOCS_DIR.length + 1).includes("/")),
  );
}

function directoriesOf(files) {
  const dirs = new Set(["."]);
  for (const path of files) {
    for (let dir = posix.dirname(path); dir !== "." && !dirs.has(dir); dir = posix.dirname(dir)) {
      dirs.add(dir);
    }
  }
  return dirs;
}

function localOnlyPaths(repo) {
  if (!repo.files.includes("local-only-paths.json")) return [];
  return JSON.parse(repo.read("local-only-paths.json")).localOnly.map((entry) => entry.path);
}

function parserFor(repo) {
  const cache = new Map();
  return (path) => {
    if (!cache.has(path)) {
      const kind = path.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS;
      const text = repo.read(path);
      cache.set(path, ts.createSourceFile(path, text, ts.ScriptTarget.Latest, false, kind));
    }
    return cache.get(path);
  };
}

function lineAt(text, offset) {
  return text.slice(0, offset).split("\n").length;
}

/* ------------------------------------------------------------------ markdown */

/** Fenced code blocks as `{ info, start, end, bodyStart, body }`; an unclosed fence runs to EOF. */
export function fencedBlocks(text) {
  const blocks = [];
  let offset = 0;
  let open = null;
  for (const line of text.split("\n")) {
    const lineEnd = offset + line.length;
    if (open === null) {
      const fence = /^[ \t]*(`{3,}|~{3,})(.*)$/.exec(line);
      if (fence !== null && !(fence[1].startsWith("`") && fence[2].includes("`"))) {
        const bodyStart = Math.min(lineEnd + 1, text.length);
        open = { marker: fence[1], info: fence[2].trim(), start: offset, bodyStart };
      }
    } else {
      const close = /^[ \t]*(`{3,}|~{3,})[ \t]*$/.exec(line);
      if (
        close !== null &&
        close[1][0] === open.marker[0] &&
        close[1].length >= open.marker.length
      ) {
        const body = text.slice(open.bodyStart, Math.max(open.bodyStart, offset - 1));
        const { info, start, bodyStart } = open;
        blocks.push({ info, start, end: lineEnd, bodyStart, body });
        open = null;
      }
    }
    offset = lineEnd + 1;
  }
  if (open !== null) {
    const { info, start, bodyStart } = open;
    blocks.push({ info, start, end: text.length, bodyStart, body: text.slice(bodyStart) });
  }
  return blocks;
}

/** Inline code spans as `{ start, end, content }`. An unmatched backtick run is literal text. */
export function inlineCodeSpans(text) {
  const spans = [];
  const run = /`+/g;
  const paragraphEnd = /\n[ \t]*\n/g;
  for (let match = run.exec(text); match !== null; match = run.exec(text)) {
    const [opener] = match;
    const from = match.index + opener.length;
    paragraphEnd.lastIndex = from;
    const limit = paragraphEnd.exec(text)?.index ?? text.length;
    const closer = new RegExp(`(?<!\`)${opener}(?!\`)`, "g");
    closer.lastIndex = from;
    const closing = closer.exec(text);
    if (closing === null || closing.index >= limit) continue;
    let content = text.slice(from, closing.index).replace(/\n/g, " ");
    if (/^ .*\S.* $/.test(content)) content = content.slice(1, -1);
    spans.push({ start: match.index, end: closing.index + opener.length, content });
    run.lastIndex = closing.index + opener.length;
  }
  return spans;
}

/** Replaces every character in the ranges except newlines with a space, preserving offsets. */
export function blank(text, ranges) {
  let out = "";
  let cursor = 0;
  for (const { start, end } of ranges.toSorted((a, b) => a.start - b.start)) {
    if (start < cursor) continue;
    out += text.slice(cursor, start) + text.slice(start, end).replace(/[^\n]/g, " ");
    cursor = end;
  }
  return out + text.slice(cursor);
}

/** Fences, the inline code spans outside them, and the prose left once both are blanked. */
export function markdownParts(text) {
  const fences = fencedBlocks(text);
  const withoutFences = blank(text, fences);
  const spans = inlineCodeSpans(withoutFences);
  return { fences, spans, withoutFences, prose: blank(withoutFences, spans) };
}

/** GitHub's heading anchor for a heading's plain text. */
export function slugify(heading) {
  return heading
    .toLowerCase()
    .replace(/[^\p{L}\p{M}\p{N}\p{Pc}\- ]/gu, "")
    .replace(/ /g, "-");
}

function plainHeading(raw) {
  return raw
    .replace(/[ \t]+#+[ \t]*$/, "")
    .replace(/!?\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/`/g, "")
    .replace(/\*\*|__|\*/g, "")
    .replace(/(^|\W)_(.+?)_(?=\W|$)/g, "$1$2")
    .replace(/<[^>]+>/g, "")
    .trim();
}

/** ATX headings with their anchors, duplicates numbered the way GitHub numbers them. */
export function headings(text) {
  const seen = new Map();
  const found = [];
  const { withoutFences } = markdownParts(text);
  for (const match of withoutFences.matchAll(/^ {0,3}#{1,6}[ \t]+(.+?)[ \t]*$/gm)) {
    const title = plainHeading(match[1]);
    const base = slugify(title);
    const count = seen.get(base) ?? 0;
    seen.set(base, count + 1);
    found.push({ title, anchor: count === 0 ? base : `${base}-${count}`, offset: match.index });
  }
  return found;
}

export function sectionKey(title) {
  return title
    .replace(/`/g, "")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/[.:]+$/, "")
    .toLowerCase();
}

/** What a citation may name: every heading and every bold lead-in, as section keys. */
export function sections(text) {
  const keys = new Set(headings(text).map((heading) => sectionKey(heading.title)));
  const { withoutFences } = markdownParts(text);
  for (const match of withoutFences.matchAll(/^\s*(?:[-*+]\s+|\d+\.\s+)?\*\*(.+?)\*\*/gm)) {
    keys.add(sectionKey(match[1]));
  }
  return keys;
}

/* --------------------------------------------------------------------- links */

function linkDestinations(prose) {
  const found = [];
  for (let at = prose.indexOf("]("); at !== -1; at = prose.indexOf("](", at + 2)) {
    let index = at + 2;
    while (prose[index] === " " || prose[index] === "\t") index += 1;
    let destination = "";
    if (prose[index] === "<") {
      const close = prose.indexOf(">", index);
      if (close !== -1) destination = prose.slice(index + 1, close);
    } else {
      let depth = 0;
      let end = index;
      while (end < prose.length && !/\s/.test(prose[end])) {
        if (prose[end] === "(") depth += 1;
        else if (prose[end] === ")") {
          if (depth === 0) break;
          depth -= 1;
        }
        end += 1;
      }
      destination = prose.slice(index, end);
    }
    if (destination !== "") found.push({ destination, offset: at });
  }
  for (const match of prose.matchAll(/^ {0,3}\[(?!\^)[^\]]+\]:[ \t]*<?([^\s>]+)>?/gm)) {
    found.push({ destination: match[1], offset: match.index });
  }
  return found;
}

/** A link destination as a repository path and anchor, or null when it leaves the repository. */
export function resolveDestination(from, destination) {
  if (/^(?:[a-z][a-z0-9+.-]*:\/\/|mailto:|tel:|data:)/i.test(destination)) return null;
  const hash = destination.indexOf("#");
  const anchor = hash === -1 ? null : destination.slice(hash + 1);
  const target = (hash === -1 ? destination : destination.slice(0, hash))
    .replace(/\?.*$/, "")
    .replace(/%([0-9a-f]{2})/gi, (_, hex) => String.fromCodePoint(Number.parseInt(hex, 16)));
  let path = from;
  if (target.startsWith("/")) path = posix.normalize(target.slice(1));
  else if (target !== "") path = posix.join(posix.dirname(from), target);
  return { path: path.replace(/\/+$/, "") || ".", anchor };
}

function checkLinks(repo, context, problems) {
  const docs = new Set(docsSet(repo.files));
  const anchors = new Map();
  const anchorsOf = (path) => {
    if (!anchors.has(path)) {
      anchors.set(path, new Set(headings(repo.read(path)).map((heading) => heading.anchor)));
    }
    return anchors.get(path);
  };
  const intoDocs = (path) =>
    path === ROOT_GUIDE || path === DOCS_DIR || path.startsWith(`${DOCS_DIR}/`);
  for (const from of repo.files) {
    if (!from.endsWith(".md") || ARCHIVED.test(from)) continue;
    const text = repo.read(from);
    for (const { destination, offset } of linkDestinations(markdownParts(text).prose)) {
      const target = resolveDestination(from, destination);
      if (target === null || (!docs.has(from) && !intoDocs(target.path))) continue;
      const report = (message) =>
        problems.push({ file: from, line: lineAt(text, offset), message });
      if (!context.fileSet.has(target.path) && !context.dirs.has(target.path)) {
        report(`link to missing ${target.path}`);
      } else if (
        target.anchor !== null &&
        target.anchor !== "" &&
        target.path.endsWith(".md") &&
        context.fileSet.has(target.path) &&
        !anchorsOf(target.path).has(target.anchor.toLowerCase())
      ) {
        report(`link to ${target.path}#${target.anchor}: no such heading`);
      }
    }
  }
}

/* ----------------------------------------------------------------- citations */

const CITATION =
  /(?<![\w./-])((?:\.\.\/)*(?:DESIGN\.md|design-system\/[\w.-]+\.md))[`'")\]]*(?:\s|\/\/|\*(?!\/)|#)+["“]([^"”\s][^"”]{0,119}?)["”]/g;

/** Every `file "Section"` citation in a text, with a section wrapped across comment lines joined. */
export function citations(text) {
  return [...text.matchAll(CITATION)].map((match) => ({
    doc: match[1].replace(/^(?:\.\.\/)+/, ""),
    section: match[2].replace(/\s*\n\s*(?:\*|\/\/|#)?\s*/g, " ").trim(),
    offset: match.index,
  }));
}

function checkCitations(repo, context, problems) {
  const known = new Map();
  for (const path of repo.files) {
    if (!CITING_FILE.test(path) || ARCHIVED.test(path) || SELF.has(path)) continue;
    const text = repo.read(path);
    for (const citation of citations(text)) {
      const report = (message) => {
        problems.push({ file: path, line: lineAt(text, citation.offset), message });
      };
      if (!context.fileSet.has(citation.doc)) {
        report(`cites missing ${citation.doc}`);
        continue;
      }
      if (!known.has(citation.doc)) known.set(citation.doc, sections(repo.read(citation.doc)));
      if (!known.get(citation.doc).has(sectionKey(citation.section))) {
        report(
          `cites ${citation.doc} "${citation.section}", which has no such heading or bold lead-in`,
        );
      }
    }
  }
}

/* ----------------------------------------------------------- paths and names */

const PATH_EXTENSION = /\.(ts|tsx|mjs|js|css|md|json)$/;

function isLocalOnly(path, localOnly) {
  return [...localOnly, "node_modules/"].some((entry) =>
    entry.endsWith("/") ? path === entry.slice(0, -1) || path.startsWith(entry) : path === entry,
  );
}

function missingPath(content, context) {
  if (/[\s*<>{}…$]/.test(content)) return null;
  const path = content
    .replace(/#.*$/, "")
    .replace(/:\d+(-\d+)?$/, "")
    .replace(/\/+$/, "");
  if (path === "" || isLocalOnly(path, context.localOnly)) return null;
  if (path.includes("/")) {
    if (context.topLevel.has(path.split("/")[0])) {
      return context.fileSet.has(path) || context.dirs.has(path) ? null : `missing path ${path}`;
    }
    if (!PATH_EXTENSION.test(path)) return null;
    return context.files.some((file) => file.endsWith(`/${path}`)) ? null : `missing path ${path}`;
  }
  if (!PATH_EXTENSION.test(path) || !/^[\w.-]+$/.test(path)) return null;
  return context.basenames.has(path) ? null : `no file named ${path}`;
}

/** Every identifier in the TypeScript sources under src/, JSX tag names included. */
function sourceIdentifiers(repo, parse) {
  const names = new Set();
  const visit = (node) => {
    if (ts.isIdentifier(node)) names.add(node.text);
    ts.forEachChild(node, visit);
  };
  for (const path of repo.files) {
    if (SOURCE_FILE.test(path)) visit(parse(path));
  }
  return names;
}

/** The code a doc presents as correct: inline spans, and fences not marked incorrect or avoid. */
function correctCode(text) {
  const { fences, spans } = markdownParts(text);
  return [
    ...spans.map((span) => ({ code: span.content, offset: span.start, inline: true })),
    ...fences
      .filter((fence) => !/\b(incorrect|avoid)\b/i.test(fence.info))
      .map((fence) => ({ code: fence.body, offset: fence.bodyStart, inline: false })),
  ];
}

function checkPathsAndNames(repo, context, problems) {
  let identifiers = null;
  const isIdentifier = (name) => {
    identifiers ??= sourceIdentifiers(repo, context.parse);
    return identifiers.has(name);
  };
  for (const path of docsSet(repo.files)) {
    const text = repo.read(path);
    for (const { code, offset, inline } of correctCode(text)) {
      const report = (message, at = 0) => {
        problems.push({ file: path, line: lineAt(text, offset + at), message });
      };
      if (inline) {
        const missing = missingPath(code, context);
        if (missing !== null) report(missing);
        const [first] = code.split(".");
        if (/^[A-Z][A-Za-z0-9]*(\.[A-Za-z0-9]+)*$/.test(code) && /[a-z]/.test(first)) {
          if (!isIdentifier(first)) {
            report(
              `\`${code}\` is not an identifier in src/; write a name that does not exist without backticks`,
            );
          }
        }
      }
      for (const tag of code.matchAll(/<([A-Z]\w*)/g)) {
        if (!isIdentifier(tag[1])) report(`<${tag[1]}> is not a component in src/`, tag.index);
      }
    }
  }
}

/* ------------------------------------------------------------- comment paths */

const COMMENTED_SOURCE = /^src\/.*\.(ts|tsx|js|jsx|mjs|cjs|css)$/;
const COMMENT_PATH = /(?<![\w./@~-])((?:[\w.()[\]-]+\/)+[\w.()[\]-]*[\w)\]])/g;
const JSX_TEXT = new Set([ts.SyntaxKind.JsxText, ts.SyntaxKind.JsxTextAllWhiteSpaces]);

/**
 * The comments in a script as `{ text, offset }`: TypeScript files a comment after a line break as
 * leading trivia of the next token, and one on the same line as trailing trivia of the last.
 */
function scriptComments(source) {
  const text = source.getFullText();
  const ranges = new Map();
  const visit = (node) => {
    if (!JSX_TEXT.has(node.kind)) {
      for (const range of [
        ...(ts.getLeadingCommentRanges(text, node.pos) ?? []),
        ...(ts.getTrailingCommentRanges(text, node.end) ?? []),
      ]) {
        ranges.set(range.pos, range.end);
      }
    }
    for (const child of node.getChildren(source)) visit(child);
  };
  visit(source);
  return [...ranges].map(([pos, end]) => ({ text: text.slice(pos, end), offset: pos }));
}

function commentsIn(path, text, parse) {
  if (!path.endsWith(".css")) return scriptComments(parse(path));
  return [...text.matchAll(/\/\*[\s\S]*?\*\//g)].map((match) => ({
    text: match[0],
    offset: match.index,
  }));
}

/**
 * A path under a tracked top-level entry must exist. A local-only path (plans/, docs/) is left
 * alone: it names the owner's working notes, and the operative rule belongs in a guide.
 */
function checkCommentPaths(repo, context, problems) {
  for (const path of repo.files) {
    if (!COMMENTED_SOURCE.test(path) || ARCHIVED.test(path)) continue;
    const text = repo.read(path);
    for (const comment of commentsIn(path, text, context.parse)) {
      for (const match of comment.text.matchAll(COMMENT_PATH)) {
        let cited = match[1].replace(/[.,;:]+$/, "");
        while (cited.endsWith(")") && cited.split("(").length < cited.split(")").length) {
          cited = cited.slice(0, -1);
        }
        while (cited.startsWith("(") && cited.split("(").length > cited.split(")").length) {
          cited = cited.slice(1);
        }
        cited = cited.replace(/\/+$/, "");
        if (cited.includes("...") || cited.startsWith("node_modules/")) continue;
        const report = (message) => {
          problems.push({ file: path, line: lineAt(text, comment.offset + match.index), message });
        };
        if (
          !isLocalOnly(cited, context.localOnly) &&
          context.topLevel.has(cited.split("/")[0]) &&
          !context.fileSet.has(cited) &&
          !context.dirs.has(cited)
        ) {
          report(`comment names missing path ${cited}`);
        }
      }
    }
  }
}

/* ------------------------------------------------------------------ examples */

function checkExamples(repo, uiModules, problems) {
  const components = new Map();
  const recipes = new Map();
  for (const entry of uiModules) {
    for (const component of entry.components) components.set(component.name, component.axes);
    for (const recipe of entry.recipes) recipes.set(recipe.name, recipe.axes);
  }
  const unknownValue = (owner, axes, axis, value) => {
    const known = axes.find((candidate) => candidate.name === axis);
    if (known === undefined || !CHECKED_AXES.has(axis) || known.values.length === 0) return null;
    if (known.values.includes(value)) return null;
    return `${owner} has no ${axis} "${value}"; it defines ${known.values.join(", ")}`;
  };
  for (const path of docsSet(repo.files)) {
    const text = repo.read(path);
    for (const { code, offset } of correctCode(text)) {
      const pairs = [];
      for (const element of code.matchAll(/<([A-Z]\w*)\b([^<>]*?)\/?>/g)) {
        const axes = components.get(element[1]);
        if (axes === undefined) continue;
        for (const attribute of element[2].matchAll(/\b(\w+)=["']([^"']*)["']/g)) {
          pairs.push([element[1], axes, attribute[1], attribute[2], element.index]);
        }
      }
      for (const call of code.matchAll(/(\w+Variants)\(\{([^}]*)\}\)/g)) {
        const axes = recipes.get(call[1]);
        if (axes === undefined) continue;
        for (const pair of call[2].matchAll(/(\w+):\s*["']([^"']*)["']/g)) {
          pairs.push([call[1], axes, pair[1], pair[2], call.index]);
        }
      }
      for (const [owner, axes, axis, value, at] of pairs) {
        const message = unknownValue(owner, axes, axis, value);
        if (message !== null) {
          problems.push({ file: path, line: lineAt(text, offset + at), message });
        }
      }
    }
  }
}

/* ----------------------------------------------------------- real-use tables */

function tableCells(row) {
  return row
    .trim()
    .replace(/^\|/, "")
    .replace(/(?<!\\)\|$/, "")
    .split(/(?<!\\)\|/)
    .map((cell) => cell.trim());
}

/**
 * Rows of every table whose header has each wanted column (lowercase), as
 * `{ line, first, values }`: the row's first cell, then its cells in the wanted columns.
 */
function tableRows(text, wanted) {
  const rows = [];
  const lines = text.split("\n");
  for (let index = 0; index < lines.length - 1; index += 1) {
    if (!lines[index].trim().startsWith("|") || !/^\s*\|?\s*:?-{3,}/.test(lines[index + 1])) {
      continue;
    }
    const header = tableCells(lines[index]).map((cell) => cell.toLowerCase());
    const columns = wanted.map((name) => header.indexOf(name));
    if (columns.includes(-1)) continue;
    for (let row = index + 2; row < lines.length && lines[row].trim().startsWith("|"); row += 1) {
      const cells = tableCells(lines[row]);
      const values = columns.map((column) => cells[column] ?? "");
      rows.push({ line: row + 1, first: cells[0] ?? "", values });
    }
  }
  return rows;
}

/** Rows of every table with a "Real uses" column, as `{ line, component, uses }`. */
export function realUseRows(text) {
  return tableRows(text, ["real uses"]).map(({ line, first, values: [uses] }) => ({
    line,
    component: first,
    uses,
  }));
}

/**
 * Rows of every table with "Component", "Classes" and "Call sites" columns, as
 * `{ line, component, classes, sites }`.
 */
export function restyleRows(text) {
  return tableRows(text, ["component", "classes", "call sites"]).map(
    ({ line, values: [component, classes, sites] }) => ({ line, component, classes, sites }),
  );
}

const RESOLVE_SUFFIXES = ["", ".ts", ".tsx", ".js", ".mjs", "/index.ts", "/index.tsx"];

function resolveImport(from, specifier, fileSet) {
  let base = null;
  if (specifier.startsWith("@/")) base = `src/${specifier.slice(2)}`;
  else if (specifier.startsWith(".")) base = posix.join(posix.dirname(from), specifier);
  if (base === null) return null;
  return RESOLVE_SUFFIXES.map((suffix) => base + suffix).find((path) => fileSet.has(path)) ?? null;
}

function hasExportModifier(node) {
  return (ts.getModifiers(node) ?? []).some((mod) => mod.kind === ts.SyntaxKind.ExportKeyword);
}

function declaredNames(statement) {
  if (ts.isVariableStatement(statement)) {
    return statement.declarationList.declarations
      .filter((declaration) => ts.isIdentifier(declaration.name))
      .map((declaration) => declaration.name.text);
  }
  const { name } = statement;
  return name !== undefined && ts.isIdentifier(name) ? [name.text] : [];
}

/** `{ local, name, typeOnly }` for each export, in source order, re-exports included. */
function exportsOf(source) {
  const found = [];
  for (const statement of source.statements) {
    if (ts.isExportDeclaration(statement)) {
      if (statement.exportClause === undefined || !ts.isNamedExports(statement.exportClause)) {
        continue;
      }
      for (const element of statement.exportClause.elements) {
        const local = (element.propertyName ?? element.name).text;
        const typeOnly = statement.isTypeOnly || element.isTypeOnly;
        found.push({ local, name: element.name.text, typeOnly });
      }
    } else if (hasExportModifier(statement)) {
      const typeOnly = ts.isTypeAliasDeclaration(statement) || ts.isInterfaceDeclaration(statement);
      for (const name of declaredNames(statement)) found.push({ local: name, name, typeOnly });
    }
  }
  return found;
}

/**
 * `{ specifier, names, locals, namespace, start }` for each import: names are the exporter's
 * names, locals the bindings this file uses, namespace the `* as` binding or null, start the
 * statement's offset.
 */
function importsOf(source) {
  const found = [];
  for (const statement of source.statements) {
    if (!ts.isImportDeclaration(statement) || !ts.isStringLiteral(statement.moduleSpecifier)) {
      continue;
    }
    const clause = statement.importClause;
    const bindings = clause?.namedBindings;
    const namespace =
      bindings !== undefined && ts.isNamespaceImport(bindings) ? bindings.name.text : null;
    const elements = bindings !== undefined && ts.isNamedImports(bindings) ? bindings.elements : [];
    const names = elements.map((element) => (element.propertyName ?? element.name).text);
    const locals = elements.map((element) => element.name.text);
    if (clause?.name !== undefined) {
      names.push("default");
      locals.push(clause.name.text);
    }
    const start = statement.getStart(source);
    found.push({ specifier: statement.moduleSpecifier.text, names, locals, namespace, start });
  }
  return found;
}

/**
 * The file a table cell entry names: the path itself, or the one tracked file ending in
 * `/entry`, so a table can cite `workflow-panel.tsx` or `requests/[id]/workflow-panel.tsx`.
 */
function resolveCited(entry, context) {
  if (context.fileSet.has(entry)) return { path: entry };
  const matches = context.files.filter((path) => path.endsWith(`/${entry}`));
  if (matches.length === 1) return { path: matches[0] };
  return { problem: matches.length === 0 ? "does not exist" : "names more than one file" };
}

/** A backticked source file, by path or by name, with an optional `:line` or `:start-end`. */
const CITED_SOURCE = /`([^`\s]+\.(?:tsx?|jsx?|mjs|cjs|css))(?::\d+(?:-\d+)?)?`/g;

/** The entries a table cell cites: its link targets, else its backticked source files. */
function citedEntries(doc, cell) {
  const linked = linkDestinations(cell)
    .map(({ destination }) => resolveDestination(doc, destination)?.path)
    .filter((path) => path !== undefined);
  if (linked.length > 0) return linked;
  return [...cell.matchAll(CITED_SOURCE)].map((match) => match[1]);
}

function checkRealUses(repo, context, problems) {
  let exporters = null;
  /* A row may name a module in its component cell (`parts/time-picker.tsx`) to mean that module's
     export where several modules export the name; otherwise ui/ owns a shared name. */
  const exportersOf = (wanted, within) => {
    if (exporters === null) {
      exporters = new Map();
      for (const path of repo.files) {
        if (!SOURCE_FILE.test(path)) continue;
        for (const { name } of exportsOf(context.parse(path))) {
          exporters.set(name, [...(exporters.get(name) ?? []), path]);
        }
      }
    }
    const found = exporters.get(wanted) ?? [];
    const named = found.filter((path) =>
      within.some((module) => path === module || path.endsWith(`/${module}`)),
    );
    if (named.length > 0) return named;
    const owned = found.filter((path) => path.startsWith(UI_DIR));
    return owned.length > 0 ? owned : found;
  };
  for (const doc of docsSet(repo.files)) {
    for (const row of realUseRows(repo.read(doc))) {
      const report = (message) => problems.push({ file: doc, line: row.line, message });
      const names = [...row.component.matchAll(/`([A-Za-z_]\w*)`/g)].map((match) => match[1]);
      const within = [...row.component.matchAll(/`([^`\s]+\.tsx?)`/g)].map((match) => match[1]);
      if (names.length === 0) continue;
      const sources = new Set();
      for (const name of names) {
        const found = exportersOf(name, within);
        if (found.length === 0) report(`\`${name}\` is not exported by any module in src/`);
        for (const path of found) sources.add(path);
      }
      for (const entry of citedEntries(doc, row.uses)) {
        const { path: use, problem } = resolveCited(entry, context);
        if (use === undefined) {
          report(`real use ${entry} ${problem}`);
          continue;
        }
        if (!/\.(ts|tsx)$/.test(use)) continue;
        const imports = importsOf(context.parse(use)).some((declaration) => {
          const target = resolveImport(use, declaration.specifier, context.fileSet);
          if (target === null || !sources.has(target)) return false;
          if (declaration.namespace !== null) return true;
          return declaration.names.some((imported) => names.includes(imported));
        });
        if (!imports) report(`real use ${use} does not import ${names.join(" or ")}`);
      }
    }
  }
}

